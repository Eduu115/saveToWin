export type ProKey = keyof typeof es

export function tp(key: ProKey, vars?: Record<string, string | number>): string {
  let text: string = es[key]
  for (const [k, v] of Object.entries(vars ?? {})) text = text.replaceAll(`{${k}}`, String(v))
  return text
}

